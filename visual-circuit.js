const $=id=>document.getElementById(id);
const list=[];
let serial={R:0,C:0,L:0,V:0};
const defaults={R:"1k",C:"1u",L:"10m",V:"DC 5"};
const esc=s=>String(s).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
function add(type,value,a,b){serial[type]=(serial[type]||0)+1;list.push({id:type+serial[type],type,value,a,b});render()}
function render(){
  $("schemList").innerHTML=list.length?list.map((c,i)=>'<div class="schem-row" data-index="'+i+'"><b>'+c.id+'</b><input data-field="value" value="'+esc(c.value)+'" aria-label="'+c.id+' value"><input data-field="a" value="'+esc(c.a)+'" aria-label="'+c.id+' node A"><input data-field="b" value="'+esc(c.b)+'" aria-label="'+c.id+' node B"><button class="subtle-btn" data-remove="'+i+'" aria-label="Remove '+c.id+'">×</button></div>').join(""):"<p class='hint'>No components yet. Add a resistor, capacitor, inductor or voltage source.</p>";
  const nodes=[...new Set(list.flatMap(c=>[c.a,c.b]))],positions={};
  nodes.forEach((n,i)=>positions[n]={x:65+(i%5)*155,y:60+Math.floor(i/5)*95});
  let svg="";
  list.forEach(c=>{
    const p=positions[c.a],q=positions[c.b],mx=(p.x+q.x)/2,my=(p.y+q.y)/2;
    svg+='<line x1="'+p.x+'" y1="'+p.y+'" x2="'+q.x+'" y2="'+q.y+'" stroke="#52718c" stroke-width="2"/>';
    svg+='<circle cx="'+p.x+'" cy="'+p.y+'" r="5" fill="#5eead4"/><circle cx="'+q.x+'" cy="'+q.y+'" r="5" fill="#5eead4"/>';
    svg+='<rect x="'+(mx-37)+'" y="'+(my-17)+'" width="74" height="34" rx="6" fill="#14283d" stroke="#5eead4"/>';
    svg+='<text x="'+mx+'" y="'+(my-2)+'" text-anchor="middle" fill="#e8eef7" font-size="12">'+esc(c.id)+'</text><text x="'+mx+'" y="'+(my+11)+'" text-anchor="middle" fill="#91a3bb" font-size="10">'+esc(c.value)+'</text>';
  });
  nodes.forEach(n=>{const p=positions[n];svg+='<text x="'+p.x+'" y="'+(p.y-12)+'" text-anchor="middle" fill="#5eead4" font-size="11">'+esc(n)+'</text>'});
  $("schemSvg").innerHTML=svg||'<text x="24" y="34" fill="#91a3bb">Add a component to begin.</text>';
}
$("schemAdd").onclick=()=>{
  const type=$("schemType").value,value=$("schemValue").value.trim(),a=$("schemNodeA").value.trim(),b=$("schemNodeB").value.trim();
  if(!value||!a||!b||a===b){alert("Enter a value and two different node names.");return}
  add(type,value,a,b);$("schemValue").value=defaults[type];$("schemNodeA").value=b;$("schemNodeB").value="0";
};
$("schemType").onchange=()=>{$("schemValue").value=defaults[$("schemType").value]};
$("schemList").addEventListener("change",e=>{
  const row=e.target.closest(".schem-row");if(!row)return;
  const item=list[Number(row.dataset.index)],field=e.target.dataset.field;
  if(!item||!field)return;item[field]=e.target.value.trim();render();
});
$("schemList").addEventListener("click",e=>{const btn=e.target.closest("[data-remove]");if(btn){list.splice(Number(btn.dataset.remove),1);render()}});
const validNode=n=>n==="0"||/^[A-Za-z_][A-Za-z0-9_]*$/.test(n);
const validNumber=v=>/^[+-]?(?:\\d+\\.?\\d*|\\.\\d+)(?:e[+-]?\\d+)?(?:meg|[tgkmunpf]|mil)?$/i.test(v);
const validValue=c=>{
  const v=c.value.trim();
  if(c.type!=="V")return validNumber(v);
  if(/^DC\\s+/i.test(v))return validNumber(v.replace(/^DC\\s+/i,""));
  if(/^AC\\s+/i.test(v))return v.replace(/^AC\\s+/i,"").trim().split(/\\s+/).every(validNumber);
  const pulse=v.match(/^PULSE\\(([^()]*)\\)$/i);
  return !!pulse&&pulse[1].trim().split(/[\\s,]+/).length===7&&pulse[1].trim().split(/[\\s,]+/).every(validNumber);
};
$("schemGenerate").onclick=()=>{
  const fail=message=>{alert(message);$("simLog").textContent="SCHEMATIC VALIDATION ERROR\\n"+message};
  if(!list.length){fail("Add at least one component.");return}
  for(const c of list){
    if(!validNode(c.a)||!validNode(c.b)){fail("Invalid node name in "+c.id+". Use letters, digits and underscores; node 0 is ground.");return}
    if(c.a===c.b){fail(c.id+" connects a node to itself.");return}
    if(!validValue(c)){fail("Invalid or unsupported value for "+c.id+". Use a numeric SPICE value; voltage sources also accept DC, AC or PULSE(...).");return}
  }
  const nodes=new Set(list.flatMap(c=>[c.a,c.b]));
  if(!nodes.has("0")){fail("No ground node found. Connect at least one component terminal to node 0.");return}
  const graph=new Map([...nodes].map(n=>[n,new Set()]));
  list.forEach(c=>{graph.get(c.a).add(c.b);graph.get(c.b).add(c.a)});
  const reached=new Set(["0"]),queue=["0"];
  while(queue.length){const n=queue.shift();for(const next of graph.get(n))if(!reached.has(next)){reached.add(next);queue.push(next)}}
  const floating=[...nodes].filter(n=>!reached.has(n));
  if(floating.length){fail("Floating/disconnected nodes: "+floating.join(", ")+". Connect every circuit section to ground or another grounded section.");return}
  const lines=["* Generated by MTDM AI Lab Visual Schematic Builder"];
  list.forEach(c=>{const sourceValue=c.value.trim().toUpperCase();const value=c.type==="V"?(sourceValue.startsWith("DC ")||sourceValue.startsWith("AC ")||sourceValue.startsWith("PULSE(")?c.value:"DC "+c.value):c.value;lines.push(c.id+" "+c.a+" "+c.b+" "+value)});
  lines.push($("schemAnalysis").value,".end");
  $("netlist").value=lines.join("\\n");
  $("probeNode").value=list.at(-1).b==="0"?list.at(-1).a:list.at(-1).b;
  $("netlist").scrollIntoView({behavior:"smooth",block:"center"});
  $("simLog").textContent="SCHEMATIC CHECK PASSED\\nComponents: "+list.length+"\\nNodes: "+nodes.size+"\\nGround: connected\\nConnectivity: all nodes reach ground\\nReview generated netlist and run simulation.";
};
render();
